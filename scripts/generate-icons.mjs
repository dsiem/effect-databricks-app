import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { writeFile } from "node:fs/promises";

// Keep only the SVGs we use. Foldkit owns their VNodes; no DOM replacement or
// icon runtime is needed. Rerun this script to regenerate from the pinned source.
const version = "0.468.0";
const source = `https://raw.githubusercontent.com/lucide-icons/lucide/${version}`;
const names = [
  "layout-dashboard",
  "table-2",
  "map",
  "book-open",
  "sparkles",
  "car-taxi-front",
  "panel-left",
  "menu",
  "x",
  "chevron-left",
  "chevron-right",
  "maximize-2",
  "minimize-2",
  "plus",
  "pencil",
  "trash-2",
  "arrow-up-right",
  "arrow-up",
  "pin",
  "pin-off",
];
async function download(path) {
  const response = await fetch(`${source}/${path}`);
  assert.ok(response.ok, `Unable to fetch ${path}: ${response.status}`);
  return response.text();
}
const icons = await Promise.all(
  names.map(async (name) => {
    const svg = await download(`icons/${name}.svg`);
    const body = svg.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/)?.[1];
    assert.ok(body, `Missing SVG body: ${name}`);
    const shapes = [...body.matchAll(/<(\w+)\s+([^>]*?)\s*\/>/g)].map(
      ([, tag, attributes]) => {
        assert.ok(
          [
            "path",
            "rect",
            "circle",
            "line",
            "polyline",
            "polygon",
            "ellipse",
          ].includes(tag),
          `Unsupported SVG element: ${tag}`,
        );
        const attrs = [...attributes.matchAll(/([\w-]+)="([^"]*)"/g)].map(
          ([, key, value]) =>
            `h.Attribute(${JSON.stringify(key)}, ${JSON.stringify(value)})`,
        );
        assert.ok(attrs.length, `Missing attributes: ${name}/${tag}`);
        return `h.${tag}([${attrs.join(", ")}], [])`;
      },
    );
    assert.ok(shapes.length, `Missing shapes: ${name}`);
    assert.equal(
      body.replace(/<(\w+)\s+([^>]*?)\s*\/>/g, "").trim(),
      "",
      `Unrecognized SVG content: ${name}`,
    );
    return `${JSON.stringify(name)}: <Message>(h: H<Message>) => [${shapes.join(",\n")}],`;
  }),
);
const license = await download("LICENSE");
const module = `// Generated by scripts/generate-icons.mjs from Lucide ${version}.
// License: client/public/lucide-LICENSE.txt
import type { H } from "./primitives";

const shapes = {
${icons.join("\n")}
};

export type IconName = keyof typeof shapes;

export const icon = <Message>(h: H<Message>, name: IconName) =>
  h.svg(
    [
      h.Class("icon"),
      h.ViewBox("0 0 24 24"),
      h.Width("16"),
      h.Height("16"),
      h.Fill("none"),
      h.Stroke("currentColor"),
      h.StrokeWidth("2"),
      h.StrokeLinecap("round"),
      h.StrokeLinejoin("round"),
      h.AriaHidden(true),
      h.Attribute("focusable", "false"),
    ],
    shapes[name](h),
  );
`;
// Use the repository formatter so regeneration produces a clean diff.
const formatted = spawnSync(
  process.execPath,
  [
    "node_modules/@biomejs/biome/bin/biome",
    "format",
    "--stdin-file-path=client/src/ui/icons.ts",
  ],
  { input: module, encoding: "utf8" },
);
assert.equal(formatted.status, 0, formatted.stderr);
await writeFile(
  new URL("../client/src/ui/icons.ts", import.meta.url),
  formatted.stdout,
);
await writeFile(
  new URL("../client/public/lucide-LICENSE.txt", import.meta.url),
  license,
);
console.log(`Generated ${names.length} Foldkit icons from Lucide ${version}.`);
